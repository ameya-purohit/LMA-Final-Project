"""Zero-cost ablations on toylib: no LLM, no quota, known ground truth.

- A6: the verdict of each planted line under all three acceptance rules.
- A11: constants-only against the full mutation operator set.
- Leniency: of the lines a claim's probe actually executes, the share each rule accepts.
  If "any flip" accepts nearly every executed line, the filter is not filtering.

Runs in the Docker sandbox. Usage: python -m analysis.toylib_ablations
"""

from __future__ import annotations

import json
import re
import sys
import textwrap
from pathlib import Path
from typing import Any

from core.config import REPO_ROOT, load_config
from sandbox.session import SandboxSession
from tools.mutate import ALL_OPERATORS, mutate_and_run

TOYLIB = REPO_ROOT / "tests" / "fixtures" / "toylib"
CORE = TOYLIB / "src" / "toylib" / "core.py"
REL = "toylib/core.py"


def _probe(expr: str, claim: str) -> str:
    return textwrap.dedent(f"""
        import pytest
        from toylib import at_least, clamp, safe_div

        def observe():
            return {expr}

        def test_claim():
            {claim}
    """)


# Each claim: planted lines with the verdict the ground truth requires under the strictest rule.
CLAIMS = [
    {"name": "C1: clamp(-1, strict=False) raises ValueError",
     "claim": _probe("clamp(-1, strict=False)", "with pytest.raises(ValueError):\n                clamp(-1, strict=False)"),
     "control": _probe("clamp(5, strict=False)", "assert clamp(5, strict=False) == 5"),
     "lines": {"decider": True, "strict_default": False, "overrides": False}},
    {"name": "C2: clamp(500, strict=False) == 100",
     "claim": _probe("clamp(500, strict=False)", "assert clamp(500, strict=False) == 100"),
     "control": _probe("clamp(5, strict=False)", "assert clamp(5, strict=False) == 5"),
     "lines": {"limit": True, "return_result": False, "min_result": True}},
    {"name": "Redundant guards: safe_div(1, 0) raises ValueError",
     "claim": _probe("safe_div(1, 0)", "with pytest.raises(ValueError):\n                safe_div(1, 0)"),
     "control": _probe("safe_div(6, 3)", "assert safe_div(6, 3) == 2.0"),
     "lines": {"guard_inline": False, "guard_helper": False}},
    {"name": "at_least(18, 18) is True",
     "claim": _probe("at_least(18, 18)", "assert at_least(18, 18) is True"),
     "control": _probe("at_least(30, 18)", "assert at_least(30, 18) is True"),
     "lines": {"compare_no_const": True}},
]


def mark_line(name: str) -> int:
    for i, line in enumerate(CORE.read_text(encoding="utf-8").splitlines(), 1):
        if re.search(rf"# MARK: {re.escape(name)}\b", line):
            return i
    raise KeyError(name)


def run_a6(session: Any) -> list[dict[str, Any]]:
    rows = []
    for c in CLAIMS:
        for mark, expected in c["lines"].items():
            line = mark_line(mark)
            full = mutate_and_run(session, REL, line, c["claim"], [c["control"]])
            consts = mutate_and_run(session, REL, line, c["claim"], [c["control"]], operators=("constant",))
            rows.append({"claim": c["name"], "line": line, "mark": mark, "ground_truth_causal": expected,
                         "n_mutants": len(full.mutants), **full.verdicts,
                         "specific_constants_only": consts.causal, "n_mutants_constants_only": len(consts.mutants)})
    return rows


def run_leniency(session: Any) -> list[dict[str, Any]]:
    """Over lines the claim's probe executes. Module-level lines ran at import, so tracing
    observe() does not see them; those are listed under A6 instead."""
    rows = []
    for c in CLAIMS:
        traced = session.run_probes([("claim", c["claim"])], trace_lines_for=[REL])["results"][0]["executed_lines"][REL]
        counts = {"any_flip": 0, "behavioural": 0, "specific": 0}
        accepted = {k: [] for k in counts}
        for line in traced:
            r = mutate_and_run(session, REL, line, c["claim"], [c["control"]], operators=ALL_OPERATORS)
            if r.error:
                continue
            for rule in counts:
                if r.verdicts[rule]:
                    counts[rule] += 1
                    accepted[rule].append(line)
        rows.append({"claim": c["name"], "executed_lines": traced, "n_executed": len(traced), "accepted": accepted,
                     **{f"share_{k}": v / len(traced) if traced else None for k, v in counts.items()}})
    return rows


def to_markdown(a6: list[dict[str, Any]], leniency: list[dict[str, Any]]) -> str:
    yn = lambda b: "accept" if b else "reject"  # noqa: E731
    lines = ["# Toylib ablations (zero API cost)", "", "Generated by `python -m analysis.toylib_ablations` in the Docker sandbox.",
             "", "## A6 and A11: each planted line under each rule", "",
             "| Claim | Line | Mark | Ground truth | any flip | behavioural | behavioural + specific | constants only (A11) |",
             "|---|---|---|---|---|---|---|---|"]
    for r in a6:
        lines.append(f"| {r['claim']} | {r['line']} | {r['mark']} | {'causal' if r['ground_truth_causal'] else 'not causal'} | "
                     f"{yn(r['any_flip'])} | {yn(r['behavioural'])} | {yn(r['specific'])} | {yn(r['specific_constants_only'])} |")
    matches = {rule: sum(r[rule] == r["ground_truth_causal"] for r in a6) for rule in ("any_flip", "behavioural", "specific")}
    matches["constants_only"] = sum(r["specific_constants_only"] == r["ground_truth_causal"] for r in a6)
    lines += ["", f"Agreement with ground truth over {len(a6)} planted lines: any flip {matches['any_flip']}, "
              f"behavioural {matches['behavioural']}, behavioural + specific {matches['specific']}, "
              f"specific with constants only {matches['constants_only']}.", "", "## Leniency: share of executed lines accepted", "",
              "| Claim | Executed lines | any flip | behavioural | behavioural + specific |", "|---|---|---|---|---|"]
    total = sum(r["n_executed"] for r in leniency)
    for r in leniency:
        lines.append(f"| {r['claim']} | {r['n_executed']} | {100 * r['share_any_flip']:.0f}% | {100 * r['share_behavioural']:.0f}% | "
                     f"{100 * r['share_specific']:.0f}% |")
    overall = {k: sum(len(r['accepted'][k]) for r in leniency) / total for k in ("any_flip", "behavioural", "specific")}
    lines.append(f"| All | {total} | {100 * overall['any_flip']:.0f}% | {100 * overall['behavioural']:.0f}% | {100 * overall['specific']:.0f}% |")
    return "\n".join(lines) + "\n"


def main() -> int:
    cfg = load_config()
    session = SandboxSession(TOYLIB, "toylib", config=cfg)
    session.start()
    try:
        a6 = run_a6(session)
        leniency = run_leniency(session)
    finally:
        session.cleanup()
    out = REPO_ROOT / "results" / "summary"
    out.mkdir(parents=True, exist_ok=True)
    (out / "toylib_ablations.json").write_text(json.dumps({"a6": a6, "leniency": leniency}, indent=1), encoding="utf-8")
    md = to_markdown(a6, leniency)
    (out / "toylib_ablations.md").write_text(md, encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
